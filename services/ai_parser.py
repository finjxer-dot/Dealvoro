# REMOVE DUPLICATES ACROSS GROUPS
# =========================================

def remove_cross_group_duplicates(
    must_groups,
    soft_groups,
    requirement_terms,
):

    used_lower = set()

    for group in must_groups:
        for term in group:
            used_lower.add(term.lower())

    cleaned_soft = []

    for group in soft_groups:

        filtered_group = []

        for term in group:

            key = term.lower()

            if key in used_lower:
                continue

            used_lower.add(key)
            filtered_group.append(term)

        if filtered_group:
            cleaned_soft.append(filtered_group)

    cleaned_requirements = []

    for term in requirement_terms:

        key = term.lower()

        if key in used_lower:
            continue

        used_lower.add(key)
        cleaned_requirements.append(term)

    return (
        cleaned_soft,
        cleaned_requirements,
    )


