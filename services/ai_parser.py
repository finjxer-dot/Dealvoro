# =========================================
# CLEAN TERMS
# =========================================

def clean_terms(
    terms
):
    """
    Очищает список терминов:

    - убирает кавычки;
    - удаляет пустые значения;
    - разбивает случайные CSV-строки;
    - убирает дубликаты.
    """

    if not terms:
        return []

    cleaned = []

    for term in terms:

        if not isinstance(
            term,
            str,
        ):
            continue

        value = term.strip()

        if not value:
            continue

        value = value.replace(
            '"',
            ""
        )

        value = value.replace(
            "'",
            ""
        )

        parts = value.split(",")

        for part in parts:

            part = part.strip()

            if part:
                cleaned.append(
                    part
                )

    result = []

    seen = set()

    for term in cleaned:

        key = term.lower()

        if key not in seen:

            seen.add(
                key
            )

            result.append(
                term
            )

    return result


# =========================================
# CLEAN MUST GROUPS
# =========================================

def clean_must_groups(
    groups
):
    """
    Очищает группы,
    сохраняя структуру:

    [
        ["nike"],
        ["кроссовки", "sneakers"]
    ]
    """

    if not groups:
        return []

    result = []

    for group in groups:

        if not isinstance(
            group,
            list,
        ):
            continue

        cleaned_group = clean_terms(
            group
        )

        if cleaned_group:

            result.append(
                cleaned_group
            )

    return result


# =========================================
# NORMALIZE AUDIENCE
# =========================================

def normalize_audience(
    audience,
) -> str:
    """
    Нормализует результат AI.

    Никаких словарей и ручного поиска
    по тексту здесь нет.

    AI сам определяет audience
    по смыслу всего запроса.
    """

    value = str(
        audience or ""
    ).strip().lower()

    if value == "child":
        return "child"

    return "adult"


