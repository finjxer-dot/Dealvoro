def clean_terms(terms):
    """
    Приводит массив терминов к нормальному виду.

    Исправляет ситуации, когда модель случайно объединила
    несколько вариантов в одну строку.
    """

    if not terms:
        return []

    cleaned = []

    for term in terms:

        if not isinstance(term, str):
            continue

        value = term.strip()

        if not value:
            continue

        value = value.replace(
            '"',
            ""
        )

        value = value.replace(
            "'",
            ""
        )

        parts = value.split(",")

        for part in parts:

            part = part.strip()

            if part:
                cleaned.append(part)

    result = []
    seen = set()

    for term in cleaned:

        key = term.lower()

        if key not in seen:

            seen.add(key)
            result.append(term)

    return result


