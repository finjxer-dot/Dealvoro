def check_query_allowed(
    product: str
) -> bool:
    """
    Проверяет,
    является ли запрос допустимым
    поиском физического товара.
    """

    if not product:

        return False

    if not os.getenv(
        "OPENAI_API_KEY"
    ):

        print(
            "OPENAI_API_KEY не найден."
        )

        return True

    try:

        response = client.responses.create(
            model="gpt-5.4-mini",
            input=[
                {
                    "role": "system",
                    "content": MODERATION_PROMPT,
                },
                {
                    "role": "user",
                    "content": product,
                },
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "dealvoro_query_moderation",
                    "strict": True,
                    "schema": {
                        "type": "object",

                        "properties": {

                            "is_product_query": {
                                "type": "boolean"
                            },

                            "is_allowed": {
                                "type": "boolean"
                            }
                        },

                        "required": [
                            "is_product_query",
                            "is_allowed"
                        ],

                        "additionalProperties": False
                    }
                }
            }
        )

        result = json.loads(
            response.output_text
        )

        return (
            bool(
                result.get(
                    "is_product_query",
                    False,
                )
            )
            and
            bool(
                result.get(
                    "is_allowed",
                    False,
                )
            )
        )

    except Exception as error:

        print(
            f"Ошибка проверки запроса: {error}"
        )

        # Временная ошибка API
        # не должна полностью ломать бота.
        return True


# =========================================
# SEARCH ANALYSIS
# =========================================

def analyze_search_request(
    product: str,
    requirements: str | None,
) -> dict:
    """
    Анализирует запрос пользователя.

    audience определяется AI:

        adult — по умолчанию;
        child — если по смыслу понятно,
                что товар предназначен ребёнку
                или подростку.

    В этой функции НЕТ словарей
    детских ключевых слов.
    """

    if not product:

        return {
            "product_query": "",
            "search_terms": [],
            "must_groups": [],
            "soft_groups": [],
            "requirements": requirements,
            "requirement_terms": [],
            "exclude_terms": [],
            "audience": "adult",
        }

    # =====================================
    # FALLBACK БЕЗ API KEY
    # =====================================

    if not os.getenv(
        "OPENAI_API_KEY"
    ):

        print(
            "OPENAI_API_KEY не найден."
        )

        # Без AI безопаснее считать запрос
        # взрослым по умолчанию.
        return {
            "product_query": product,

            "search_terms": [
                product
            ],

            "must_groups": [
                [product]
            ],

            "soft_groups": [],

            "requirements": requirements,

            "requirement_terms": (
                [requirements]
                if requirements
                else []
            ),

            "exclude_terms": [],

            "audience": "adult",
        }

    # =====================================
    # USER TEXT
    # =====================================

    user_text = (
        "Основной запрос пользователя:\n"
        f"{product}\n\n"
        "Дополнительные требования пользователя:\n"
        f"{requirements if requirements else 'нет'}"
    )

    try:

        response = client.responses.create(
            model="gpt-5.4-mini",
            input=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": user_text,
                },
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "dealvoro_search_analysis",
                    "strict": True,
                    "schema": {
                        "type": "object",

                        "properties": {

                            "product_query": {
                                "type": "string"
                            },

                            "search_terms": {
                                "type": "array",
                                "items": {
                                    "type": "string"
                                },
                                "minItems": 1,
                                "maxItems": 8
                            },

                            "must_groups": {
                                "type": "array",
                                "items": {
                                    "type": "array",
                                    "items": {
                                        "type": "string"
                                    },
                                    "minItems": 1,
                                    "maxItems": 15
                                },
                                "minItems": 1,
                                "maxItems": 15
                            },

                            "soft_groups": {
                                "type": "array",
                                "items": {
                                    "type": "array",
                                    "items": {
                                        "type": "string"
                                    },
                                    "minItems": 1,
                                    "maxItems": 15
                                },
                                "maxItems": 15
                            },

                            "requirements": {
                                "type": [
                                    "string",
                                    "null"
                                ]
                            },

                            "requirement_terms": {
                                "type": "array",
                                "items": {
                                    "type": "string"
                                },
                                "maxItems": 15
                            },

                            "exclude_terms": {
                                "type": "array",
                                "items": {
                                    "type": "string"
                                },
                                "maxItems": 40
                            },

                            "audience": {
                                "type": "string",
                                "enum": [
                                    "adult",
                                    "child"
                                ]
                            }
                        },

                        "required": [
                            "product_query",
                            "search_terms",
                            "must_groups",
                            "soft_groups",
                            "requirements",
                            "requirement_terms",
                            "exclude_terms",
                            "audience"
                        ],

                        "additionalProperties": False
                    }
                }
            }
        )

        result = json.loads(
            response.output_text
        )

        # =====================================
        # PRODUCT QUERY
        # =====================================

        product_query = str(
            result.get(
                "product_query",
                product,
            )
        ).strip()

        if not product_query:

            product_query = product

        # =====================================
        # SEARCH TERMS
        # =====================================

        search_terms = clean_terms(
            result.get(
                "search_terms",
                [],
            )
        )

        if not search_terms:

            search_terms = [
                product_query
            ]

        # =====================================
        # MUST GROUPS
        # =====================================

        must_groups = clean_must_groups(
            result.get(
                "must_groups",
                [],
            )
        )

        if not must_groups:

            must_groups = [
                [
                    product_query
                ]
            ]

        # =====================================
        # SOFT GROUPS
        # =====================================

        soft_groups = clean_soft_groups(
            result.get(
                "soft_groups",
                [],
            )
        )

        # =====================================
        # REQUIREMENTS
        # =====================================

        parsed_requirements = result.get(
            "requirements"
        )

        if parsed_requirements:

            parsed_requirements = str(
                parsed_requirements
            ).strip()

            if not parsed_requirements:

                parsed_requirements = None

        else:

            parsed_requirements = None

        # =====================================
        # REQUIREMENT TERMS
        # =====================================

        requirement_terms = clean_terms(
            result.get(
                "requirement_terms",
                []
            )
        )

        # =====================================
        # AUDIENCE
        # =====================================

        audience = normalize_audience(
            result.get(
                "audience",
                "adult",
            )
        )

        # =====================================
        # EXCLUDE TERMS
        # =====================================

        exclude_terms = clean_terms(
            result.get(
                "exclude_terms",
                []
            )
        )

        # =====================================
        # УДАЛЕНИЕ КОНФЛИКТОВ
        # =====================================

        must_term_lower = {
            group_term.lower()
            for group in must_groups
            for group_term in group
        }

        soft_term_lower = {
            group_term.lower()
            for group in soft_groups
            for group_term in group
        }

        cleaned_exclude_terms = []

        for term in exclude_terms:

            term_lower = term.lower()

            if term_lower in must_term_lower:
                continue

            if term_lower in soft_term_lower:
                continue

            cleaned_exclude_terms.append(
                term
            )

        exclude_terms = (
            cleaned_exclude_terms
        )

        # =====================================
        # RESULT
        # =====================================

        return {

            "product_query": (
                product_query
            ),

            "search_terms": (
                search_terms
            ),

            "must_groups": (
                must_groups
            ),

            "soft_groups": (
                soft_groups
            ),

            "requirements": (
                parsed_requirements
            ),

            "requirement_terms": (
                requirement_terms
            ),

            "exclude_terms": (
                exclude_terms
            ),

            "audience": (
                audience
            ),
        }

    except Exception as error:

        print(
            f"Ошибка OpenAI-анализа: {error}"
        )

        # =====================================
        # FALLBACK ПРИ ОШИБКЕ API
        # =====================================

        return {

            "product_query": product,

            "search_terms": [
                product
            ],

            "must_groups": [
                [product]
            ],

            "soft_groups": [],

            "requirements": requirements,

            "requirement_terms": (
                [requirements]
                if requirements
                else []
            ),

            "exclude_terms": [],

            "audience": "adult",
        }