# REMOVE FORBIDDEN TERMS FROM GROUPS
# =========================================

def remove_modifiers_from_groups(
    must_groups,
    product_query,
):
    """
    Программно удаляет запрещённые слова
    из must_groups.

    Логика:

    - Из ПЕРВОЙ группы (must_groups[0] —
      тип товара) удаляются:

      * MODIFIER_TERMS;
      * GENERIC_TERMS;
      * РУССКИЕ ФОРМЫ (is_russian_form).

    - Из ОСТАЛЬНЫХ групп (модель, бренд,
      цвет, пол) НИЧЕГО не удаляется.
      Там "pro", "max", "mini", "ultra"
      могут быть частью МОДЕЛИ.

    - Если первая группа после чистки
      стала пустой — в неё добавляется
      product_query как fallback.
    """

    if not must_groups:
        return must_groups

    cleaned = []

    for index, group in enumerate(must_groups):

        if not isinstance(group, list):
            continue

        is_first_group = (index == 0)

        if not is_first_group:

            # Остальные группы НЕ трогаем
            cleaned.append(list(group))
            continue

        # =====================================
        # ПЕРВАЯ ГРУППА — чистим
        # =====================================

        filtered = []

        for term in group:

            if not isinstance(term, str):
                continue

            key = term.strip().lower()

            if not key:
                continue

            if key in MODIFIER_TERMS:
                continue

            if key in GENERIC_TERMS:
                continue

            if is_russian_form(term):
                continue

            filtered.append(term)

        if not filtered and product_query:

            filtered.append(product_query)

        if filtered:
            cleaned.append(filtered)

    return cleaned


# =========================================
# ENSURE PRODUCT QUERY IN FIRST GROUP
# =========================================

def ensure_product_query_in_first_group(
    must_groups,
    product_query,
):
    if not product_query:
        return must_groups

    normalized_query = product_query.strip().lower()

    if not normalized_query:
        return must_groups

    query_words = [
        word for word in normalized_query.split()
        if word
    ]

    if not must_groups:

        return [[product_query]]

    first_group = must_groups[0]

    if not isinstance(first_group, list):

        return [[product_query]] + list(must_groups[1:])

    for term in first_group:

        if not isinstance(term, str):
            continue

        normalized_term = term.strip().lower()

        if not normalized_term:
            continue

        term_words = [
            word for word in normalized_term.split()
            if word
        ]

        for word in query_words:

            if word in term_words:
                return must_groups

        for word in query_words:

            for term_word in term_words:

                if (
                    len(word) >= 4
                    and len(term_word) >= 4
                    and term_word.startswith(word[:4])
                ):

                    return must_groups

    new_first_group = [product_query] + list(first_group)

    return [new_first_group] + list(must_groups[1:])


