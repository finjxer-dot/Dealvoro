# =========================================
# SEARCH ANALYSIS
# =========================================

def analyze_search_request(
    product: str,
    requirements: str | None,
) -> dict:

    if not product:

        return {
            "product_query": "",
            "search_terms": [],
            "must_groups": [],
            "soft_groups": [],
            "requirements": requirements,
            "requirement_terms": [],
            "exclude_terms": [],
            "audience": "adult",
        }

    if not os.getenv("OPENAI_API_KEY"):

        print("OPENAI_API_KEY не найден.")

        return {
            "product_query": product,
            "search_terms": [product],
            "must_groups": [[product]],
            "soft_groups": [],
            "requirements": requirements,
            "requirement_terms": (
                [requirements] if requirements else []
            ),
            "exclude_terms": [],
            "audience": "adult",
        }

    user_text = (
        "Основной запрос пользователя:\n"
        f"{product}\n\n"
        "Дополнительные требования пользователя:\n"
        f"{requirements if requirements else 'нет'}"
    )

    try:

        response = client.responses.create(
            model="gpt-5.4-mini",
            input=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": user_text,
                },
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "dealvoro_search_analysis",
                    "strict": True,
                    "schema": {
                        "type": "object",
                        "properties": {
                            "product_query": {"type": "string"},
                            "search_terms": {
                                "type": "array",
                                "items": {"type": "string"},
                                "minItems": 1,
                                "maxItems": 8,
                            },
                            "must_groups": {
                                "type": "array",
                                "items": {
                                    "type": "array",
                                    "items": {"type": "string"},
                                    "minItems": 1,
                                    "maxItems": 15,
                                },
                                "minItems": 1,
                                "maxItems": 15,
                            },
                            "soft_groups": {
                                "type": "array",
                                "items": {
                                    "type": "array",
                                    "items": {"type": "string"},
                                    "minItems": 1,
                                    "maxItems": 15,
                                },
                                "maxItems": 15,
                            },
                            "requirements": {
                                "type": ["string", "null"]
                            },
                            "requirement_terms": {
                                "type": "array",
                                "items": {"type": "string"},
                                "maxItems": 15,
                            },
                            "exclude_terms": {
                                "type": "array",
                                "items": {"type": "string"},
                                "maxItems": 40,
                            },
                            "audience": {
                                "type": "string",
                                "enum": ["adult", "child"],
                            },
                        },
                        "required": [
                            "product_query",
                            "search_terms",
                            "must_groups",
                            "soft_groups",
                            "requirements",
                            "requirement_terms",
                            "exclude_terms",
                            "audience",
                        ],
                        "additionalProperties": False,
                    },
                }
            },
        )

        result = json.loads(response.output_text)

        product_query = str(
            result.get("product_query", product)
        ).strip()

        if not product_query:
            product_query = product

        search_terms = clean_terms(
            result.get("search_terms", [])
        )

        if not search_terms:
            search_terms = [product_query]

        must_groups = clean_groups(
            result.get("must_groups", [])
        )

        if not must_groups:
            must_groups = [[product_query]]

        must_groups = remove_modifiers_from_groups(
            must_groups,
            product_query,
        )

        if not must_groups:
            must_groups = [[product_query]]

        must_groups = ensure_product_query_in_first_group(
            must_groups,
            product_query,
        )

        if not must_groups:
            must_groups = [[product_query]]

        if must_groups and must_groups[0]:

            first_group = must_groups[0]

            extra_forms = expand_ukrainian_forms(
                first_group
            )

            if extra_forms:

                seen = {
                    t.lower().strip()
                    for t in first_group
                }

                for form in extra_forms:

                    key = form.lower().strip()

                    if key and key not in seen:

                        seen.add(key)
                        first_group.append(form)

                must_groups[0] = first_group

                print(
                    f"[UKR] добавлено "
                    f"{len(extra_forms)} форм"
                )

        soft_groups = clean_groups(
            result.get("soft_groups", [])
        )

        parsed_requirements = result.get("requirements")

        if parsed_requirements:

            parsed_requirements = str(parsed_requirements).strip()

            if not parsed_requirements:
                parsed_requirements = None

        else:
            parsed_requirements = None

        requirement_terms = clean_terms(
            result.get("requirement_terms", [])
        )

        audience = normalize_audience(
            result.get("audience", "adult")
        )

        exclude_terms = clean_terms(
            result.get("exclude_terms", [])
        )

        soft_groups, requirement_terms = (
            remove_cross_group_duplicates(
                must_groups,
                soft_groups,
                requirement_terms,
            )
        )

        must_term_lower = {
            group_term.lower()
            for group in must_groups
            for group_term in group
        }

        soft_term_lower = {
            group_term.lower()
            for group in soft_groups
            for group_term in group
        }

        cleaned_exclude_terms = []

        for term in exclude_terms:

            term_lower = term.lower()

            if term_lower in must_term_lower:
                continue

            if term_lower in soft_term_lower:
                continue

            cleaned_exclude_terms.append(term)

        exclude_terms = cleaned_exclude_terms

        return {
            "product_query": product_query,
            "search_terms": search_terms,
            "must_groups": must_groups,
            "soft_groups": soft_groups,
            "requirements": parsed_requirements,
            "requirement_terms": requirement_terms,
            "exclude_terms": exclude_terms,
            "audience": audience,
        }

    except Exception as error:

        print(f"Ошибка OpenAI-анализа: {error}")

        return {
            "product_query": product,
            "search_terms": [product],
            "must_groups": [[product]],
            "soft_groups": [],
            "requirements": requirements,
            "requirement_terms": (
                [requirements] if requirements else []
            ),
            "exclude_terms": [],
            "audience": "adult",
        }