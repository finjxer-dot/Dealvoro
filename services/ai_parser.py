def check_query_allowed(
    product: str
) -> bool:
    """
    Проверяет,
    является ли запрос допустимым
    поиском физического товара.
    """

    if not product:

        return False

    if not os.getenv(
        "OPENAI_API_KEY"
    ):

        print(
            "OPENAI_API_KEY не найден."
        )

        return True

    try:

        response = client.responses.create(
            model="gpt-5.4-mini",
            input=[
                {
                    "role": "system",
                    "content": MODERATION_PROMPT,
                },
                {
                    "role": "user",
                    "content": product,
                },
            ],
            text={
                "format": {
                    "type": "json_schema",
                    "name": "dealvoro_query_moderation",
                    "strict": True,
                    "schema": {
                        "type": "object",

                        "properties": {

                            "is_product_query": {
                                "type": "boolean"
                            },

                            "is_allowed": {
                                "type": "boolean"
                            }
                        },

                        "required": [
                            "is_product_query",
                            "is_allowed"
                        ],

                        "additionalProperties": False
                    }
                }
            }
        )

        result = json.loads(
            response.output_text
        )

        return (
            bool(
                result.get(
                    "is_product_query",
                    False,
                )
            )
            and
            bool(
                result.get(
                    "is_allowed",
                    False,
                )
            )
        )

    except Exception as error:

        print(
            f"Ошибка проверки запроса: {error}"
        )

        # Временная ошибка API
        # не должна полностью ломать бота.
        return True


