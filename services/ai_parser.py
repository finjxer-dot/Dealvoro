# =========================================
# CLEAN TERMS
# =========================================

def clean_terms(terms):
    if not terms:
        return []

    cleaned = []

    for term in terms:

        if not isinstance(term, str):
            continue

        value = term.strip()

        if not value:
            continue

        value = value.replace('"', "").replace("'", "")

        parts = value.split(",")

        for part in parts:

            part = part.strip()

            if part:
                cleaned.append(part)

    result = []

    seen = set()

    for term in cleaned:

        key = term.lower()

        if key not in seen:

            seen.add(key)
            result.append(term)

    return result


# =========================================
# CLEAN GROUPS
# =========================================

def clean_groups(groups):
    if not groups:
        return []

    result = []

    for group in groups:

        if not isinstance(group, list):
            continue

        cleaned_group = clean_terms(group)

        if cleaned_group:
            result.append(cleaned_group)

    return result


# =========================================
# IS RUSSIAN FORM
# =========================================

def is_russian_form(term: str) -> bool:
    if not term or not isinstance(term, str):
        return False

    normalized = term.strip().lower()

    if not normalized:
        return False

    russian_only_chars = set("ыъэё")

    for char in normalized:

        if char in russian_only_chars:
            return True

    russian_suffixes = (
        "ый", "ая", "ое", "ые",
        "ов", "ев",
    )

    for suffix in russian_suffixes:

        if normalized.endswith(suffix):
            return True

    return False


